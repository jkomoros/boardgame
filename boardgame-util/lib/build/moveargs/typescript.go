package moveargs

import (
	"strings"
	"unicode"
)

// MoveFieldInfo describes a single field on a move struct.
type MoveFieldInfo struct {
	Name     string `json:"name"`
	Type     string `json:"type"` // "int", "bool", "string", "playerIndex", "enum"
	EnumName string `json:"enumName,omitempty"`
}

// MoveInfo describes a single move's name and fields.
type MoveInfo struct {
	Name   string          `json:"name"`
	Fields []MoveFieldInfo `json:"fields"`
}

// GenerateTypeScript produces the contents of a _move_args.ts file given a
// list of moves with their fields. This provides typed argument interfaces for
// each move and a mapped type that connects move names to their args.
func GenerateTypeScript(moves []MoveInfo) string {
	if len(moves) == 0 {
		return typeScriptHeader + typeScriptEmptyBody
	}

	var b strings.Builder
	b.WriteString(typeScriptHeader)
	b.WriteString("import type { MoveName } from './_move_names.js';\n\n")

	// Generate an interface per move
	for _, move := range moves {
		if len(move.Fields) == 0 {
			continue
		}
		ifaceName := toPascalCase(move.Name) + "Args"
		b.WriteString("export interface ")
		b.WriteString(ifaceName)
		b.WriteString(" {\n")
		for _, field := range move.Fields {
			b.WriteString("  ")
			b.WriteString(field.Name)
			b.WriteString(": ")
			b.WriteString(fieldTypeToTS(field))
			b.WriteString(";\n")
		}
		b.WriteString("}\n\n")
	}

	// Generate the mapped type
	b.WriteString("/** Maps move names to their typed argument interfaces. */\n")
	b.WriteString("export type MoveArgs = {\n")
	for _, move := range moves {
		key := move.Name
		var valueType string
		if len(move.Fields) == 0 {
			valueType = "Record<string, never>"
		} else {
			valueType = toPascalCase(move.Name) + "Args"
		}
		b.WriteString("  \"")
		b.WriteString(key)
		b.WriteString("\": ")
		b.WriteString(valueType)
		b.WriteString(";\n")
	}
	b.WriteString("};\n")

	return b.String()
}

// fieldTypeToTS maps a Go property type string to a TypeScript type.
func fieldTypeToTS(field MoveFieldInfo) string {
	switch field.Type {
	case "int", "playerIndex":
		return "number"
	case "bool":
		return "boolean"
	case "enum":
		return "string"
	case "string":
		return "string"
	default:
		return "unknown"
	}
}

// toPascalCase converts a move name like "Reveal Card" to "RevealCard".
func toPascalCase(name string) string {
	words := strings.Fields(name)
	var b strings.Builder
	for _, word := range words {
		var cleaned []rune
		for _, r := range word {
			if unicode.IsLetter(r) || unicode.IsDigit(r) {
				cleaned = append(cleaned, r)
			}
		}
		if len(cleaned) == 0 {
			continue
		}
		cleaned[0] = unicode.ToUpper(cleaned[0])
		b.WriteString(string(cleaned))
	}
	return b.String()
}

const typeScriptHeader = `/*
 * Auto-generated by boardgame-util. DO NOT EDIT.
 */

`

const typeScriptEmptyBody = `import type { MoveName } from './_move_names.js';

export type MoveArgs = Record<MoveName, Record<string, never>>;
`
