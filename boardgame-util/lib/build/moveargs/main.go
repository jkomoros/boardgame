package moveargs

import (
	"bytes"
	"encoding/json"
	"errors"
	"go/format"
	"io/ioutil"
	"os"
	"os/exec"
	"path/filepath"
	"text/template"

	"github.com/jkomoros/boardgame/boardgame-util/lib/gamepkg"
)

const subFolder = "moveargs"

// MoveArgsResult is the result of extracting move arguments for a single game package.
type MoveArgsResult struct {
	PackageName       string                 `json:"packageName"`
	ImportPath        string                 `json:"importPath"`
	Moves             []MoveInfo             `json:"moves"`
	ChoiceProjections []ChoiceProjectionInfo `json:"choiceProjections"`
}

// Build generates a temporary Go binary that imports all game packages,
// instantiates GameManagers with in-memory storage, and extracts
// non-FixUp move field info. It returns the results as a slice of MoveArgsResult.
func Build(directory string, pkgs []*gamepkg.Pkg) ([]MoveArgsResult, error) {

	if _, err := os.Stat(directory); os.IsNotExist(err) {
		return nil, errors.New("the provided directory, " + directory + " does not exist")
	}

	code, err := Code(pkgs)

	if err != nil {
		return nil, errors.New("couldn't generate code: " + err.Error())
	}

	dir := filepath.Join(directory, subFolder)

	if _, err := os.Stat(dir); os.IsNotExist(err) {
		if err := os.Mkdir(dir, 0700); err != nil {
			return nil, errors.New("couldn't create moveargs directory: " + err.Error())
		}
	}

	codePath := filepath.Join(dir, "main.go")

	if err := ioutil.WriteFile(codePath, code, 0644); err != nil {
		return nil, errors.New("couldn't save code: " + err.Error())
	}

	// Resolve imports from the caller's module or workspace, not from the
	// generated source directory. The latter may live in the OS temp directory.
	binaryName := filepath.Join(dir, subFolder)
	cmd := exec.Command("go", "build", "-o", binaryName, codePath)

	errBuf := new(bytes.Buffer)
	cmd.Stderr = errBuf

	err = cmd.Run()

	if err != nil {
		return nil, errors.New("couldn't build moveargs binary: " + err.Error() + ": " + errBuf.String())
	}

	if _, err := os.Stat(binaryName); os.IsNotExist(err) {
		return nil, errors.New("sanity check failed: binary does not appear to have been created")
	}

	absBinaryName, err := filepath.Abs(binaryName)
	if err != nil {
		return nil, errors.New("couldn't get absolute path to binary: " + err.Error())
	}

	cmd = exec.Command(absBinaryName)
	cmd.Dir = dir

	outBuf := new(bytes.Buffer)
	errBuf = new(bytes.Buffer)
	cmd.Stdout = outBuf
	cmd.Stderr = errBuf

	err = cmd.Run()

	if err != nil {
		return nil, errors.New("couldn't run moveargs binary: " + err.Error() + ": " + errBuf.String())
	}

	var results []MoveArgsResult

	if err := json.Unmarshal(outBuf.Bytes(), &results); err != nil {
		return nil, errors.New("couldn't parse moveargs output: " + err.Error())
	}

	return results, nil
}

// Code returns the source code for a temporary Go binary that extracts move
// field info from the given game packages.
func Code(pkgs []*gamepkg.Pkg) ([]byte, error) {

	buf := new(bytes.Buffer)

	err := codeTemplate.Execute(buf, map[string]interface{}{
		"pkgs": pkgs,
	})

	if err != nil {
		return nil, errors.New("couldn't execute code template: " + err.Error())
	}

	formatted, err := format.Source(buf.Bytes())

	if err != nil {
		return nil, errors.New("couldn't format code output: " + err.Error())
	}

	return formatted, nil
}

// Clean removes the moveargs/ directory that was generated within directory
// by Build.
func Clean(directory string) error {
	return os.RemoveAll(filepath.Join(directory, subFolder))
}

var codeTemplate = template.Must(template.New("moveargs").Parse(codeTemplateText))

var codeTemplateText = `/*

A temporary binary generated by boardgame-util to extract move field info from game packages.

*/
package main

import (
	"encoding/json"
	"fmt"
	"os"

	"github.com/jkomoros/boardgame"
	memorystorage "github.com/jkomoros/boardgame/storage/memory"
	{{- range .pkgs}}
	"{{.Import}}"
	{{- end}}
)

type delegateEntry struct {
	delegate   boardgame.GameDelegate
	importPath string
}

type moveArgsResult struct {
	PackageName       string                                      ` + "`" + `json:"packageName"` + "`" + `
	ImportPath        string                                      ` + "`" + `json:"importPath"` + "`" + `
	Moves             []boardgame.MoveInputSchemaMove             ` + "`" + `json:"moves"` + "`" + `
	ChoiceProjections []boardgame.MoveChoiceProjectionSchema      ` + "`" + `json:"choiceProjections"` + "`" + `
}

func main() {
	entries := []delegateEntry{
		{{- range .pkgs}}
		{delegate: {{.Name}}.NewDelegate(), importPath: "{{.Import}}"},
		{{- end}}
	}

	var results []moveArgsResult

	for _, entry := range entries {
		storage := memorystorage.NewStorageManager()
		manager, err := boardgame.NewGameManager(entry.delegate, storage)
		if err != nil {
			fmt.Fprintf(os.Stderr, "Couldn't create manager for %s: %v\n", entry.delegate.Name(), err)
			os.Exit(1)
		}

		moves, err := boardgame.BuildMoveInputSchema(manager)
		if err != nil {
			fmt.Fprintf(os.Stderr, "Couldn't resolve creator inputs for %s: %v\n", entry.delegate.Name(), err)
			os.Exit(1)
		}
		choiceProjections, err := boardgame.BuildMoveChoiceProjectionSchema(manager)
		if err != nil {
			fmt.Fprintf(os.Stderr, "Couldn't resolve move choices for %s: %v\n", entry.delegate.Name(), err)
			os.Exit(1)
		}

		results = append(results, moveArgsResult{
			PackageName:       entry.delegate.Name(),
			ImportPath:        entry.importPath,
			Moves:             moves,
			ChoiceProjections: choiceProjections,
		})
	}

	encoder := json.NewEncoder(os.Stdout)
	if err := encoder.Encode(results); err != nil {
		fmt.Fprintf(os.Stderr, "Error encoding results: %v\n", err)
		os.Exit(1)
	}
}
`
