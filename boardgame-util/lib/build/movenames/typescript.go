package movenames

import (
	"strconv"
	"strings"
	"unicode"
)

// GenerateTypeScript keeps player-proposable names separate from transition
// keys, which additionally include fixups and configured hidden-name aliases.
// Omitting animationKeys preserves compatibility for callers with only names.
func GenerateTypeScript(moveNames []string, animationKeys ...[]string) string {
	keys := moveNames
	if len(animationKeys) > 0 {
		keys = animationKeys[0]
	}
	var b strings.Builder
	b.WriteString(typeScriptHeader)
	writeConstants(&b, "MoveNames", "MoveName", moveNames)
	b.WriteString("\n/** Animation vocabulary only; fixups and hidden-name aliases are not proposals. */\n")
	writeConstants(&b, "AnimationKeys", "AnimationKey", keys)
	return b.String()
}

func writeConstants(b *strings.Builder, plural, singular string, names []string) {
	b.WriteString("export const " + plural + " = {")
	seen := make(map[string]bool)
	identifiers := make(map[string]map[string]bool)
	for _, name := range names {
		key := toPascalCase(name)
		if identifiers[key] == nil {
			identifiers[key] = make(map[string]bool)
		}
		identifiers[key][name] = true
	}
	if len(names) > 0 {
		b.WriteString("\n")
	}
	for _, name := range names {
		if seen[name] {
			continue
		}
		seen[name] = true
		key := toPascalCase(name)
		// Preserve every value when punctuation collapses distinct names to the
		// same identifier. Exact quoted keys are always valid TypeScript.
		if len(identifiers[key]) > 1 {
			key = strconv.Quote(name)
		} else if key == "" || unicode.IsDigit([]rune(key)[0]) {
			key = strconv.Quote(key)
		}
		b.WriteString("  " + key + ": " + strconv.Quote(name) + ",\n")
	}
	b.WriteString("} as const;\n\n")
	b.WriteString("export type " + singular + " = typeof " + plural + "[keyof typeof " + plural + "];\n")
}

// toPascalCase converts a move name like "Reveal Card" to "RevealCard".
// It splits on whitespace, strips non-alphanumeric characters, capitalizes the
// first letter of each word, and joins.
func toPascalCase(name string) string {
	words := strings.Fields(name)
	var b strings.Builder

	for _, word := range words {
		// Strip non-alphanumeric characters
		var cleaned []rune
		for _, r := range word {
			if unicode.IsLetter(r) || unicode.IsDigit(r) {
				cleaned = append(cleaned, r)
			}
		}
		if len(cleaned) == 0 {
			continue
		}
		// Capitalize first letter, keep rest as-is
		cleaned[0] = unicode.ToUpper(cleaned[0])
		b.WriteString(string(cleaned))
	}

	return b.String()
}

const typeScriptHeader = `/*
 * Auto-generated by boardgame-util. DO NOT EDIT.
 */

`
