const subFolder = "gametypes"

// FieldInfo describes a single field on a game or player state.
type FieldInfo struct {
	Name     string `json:"name"`
	Type     string `json:"type"`
	DeckName string `json:"deckName,omitempty"`
	EnumName string `json:"enumName,omitempty"`
}

// DeckInfo describes a deck and its component value fields.
type DeckInfo struct {
	Name          string      `json:"name"`
	Fields        []FieldInfo `json:"fields"`
	DynamicFields []FieldInfo `json:"dynamicFields,omitempty"`
}

// EnumInfo describes an enum and its string values.
type EnumInfo struct {
	Name   string   `json:"name"`
	Values []string `json:"values"`
}

// ConstantInfo describes a configured game constant and its exact primitive
// value. ConfigureConstants only accepts int, bool, and string values.
type ConstantInfo struct {
	Name  string `json:"name"`
	Kind  string `json:"kind"`
	Value string `json:"value"`
}

// TypeResult is the result of extracting type information for a single game package.
type TypeResult struct {
	PackageName          string         `json:"packageName"`
	ImportPath           string         `json:"importPath"`
	GameFields           []FieldInfo    `json:"gameFields"`
	PlayerFields         []FieldInfo    `json:"playerFields"`
	Decks                []DeckInfo     `json:"decks"`
	Enums                []EnumInfo     `json:"enums"`
	Constants            []ConstantInfo `json:"constants"`
	GameComputedFields   []FieldInfo    `json:"gameComputedFields"`
	PlayerComputedFields []FieldInfo    `json:"playerComputedFields"`
}

// Build generates a temporary Go binary that imports all game packages,
// instantiates GameManagers with in-memory storage, and extracts type
// information. It returns the results as a slice of TypeResult.
func Build(directory string, pkgs []*gamepkg.Pkg) ([]TypeResult, error) {

	if _, err := os.Stat(directory); os.IsNotExist(err) {
		return nil, fmt.Errorf("the provided directory %s does not exist", directory)
	}

	code, err := Code(pkgs)

	if err != nil {
		return nil, fmt.Errorf("couldn't generate code: %w", err)
	}

	dir := filepath.Join(directory, subFolder)

	if _, err := os.Stat(dir); os.IsNotExist(err) {
		if err := os.Mkdir(dir, 0700); err != nil {
			return nil, fmt.Errorf("couldn't create gametypes directory: %w", err)
		}
	}

	codePath := filepath.Join(dir, "main.go")

	if err := os.WriteFile(codePath, code, 0644); err != nil {
		return nil, fmt.Errorf("couldn't save code: %w", err)
	}

	// Resolve imports from the caller's module or workspace, not from the
	// generated source directory. The latter may live in the OS temp directory.
	binaryName := filepath.Join(dir, subFolder)
	cmd := exec.Command("go", "build", "-o", binaryName, codePath)

	errBuf := new(bytes.Buffer)
	cmd.Stderr = errBuf

	err = cmd.Run()

	if err != nil {
		return nil, fmt.Errorf("couldn't build gametypes binary: %w: %s", err, errBuf.String())
	}

	if _, err := os.Stat(binaryName); os.IsNotExist(err) {
		return nil, fmt.Errorf("sanity check failed: binary does not appear to have been created")
	}

	absBinaryName, err := filepath.Abs(binaryName)
	if err != nil {
		return nil, fmt.Errorf("couldn't get absolute path to binary: %w", err)
	}

	cmd = exec.Command(absBinaryName)
	cmd.Dir = dir

	outBuf := new(bytes.Buffer)
	errBuf = new(bytes.Buffer)
	cmd.Stdout = outBuf
	cmd.Stderr = errBuf

	err = cmd.Run()

	if err != nil {
		return nil, fmt.Errorf("couldn't run gametypes binary: %w: %s", err, errBuf.String())
	}

	var results []TypeResult

	if err := json.Unmarshal(outBuf.Bytes(), &results); err != nil {
		return nil, fmt.Errorf("couldn't parse gametypes output: %w", err)
	}

	return results, nil
}

// Code returns the source code for a temporary Go binary that extracts type
// information from the given game packages.
func Code(pkgs []*gamepkg.Pkg) ([]byte, error) {

	buf := new(bytes.Buffer)

	err := codeTemplate.Execute(buf, map[string]interface{}{
		"pkgs": pkgs,
	})

	if err != nil {
		return nil, fmt.Errorf("couldn't execute code template: %w", err)
	}

	formatted, err := format.Source(buf.Bytes())

	if err != nil {
		return nil, fmt.Errorf("couldn't format code output: %w", err)
	}

	return formatted, nil
}

