package gametypes

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"text/template"

	"github.com/jkomoros/boardgame/boardgame-util/lib/gamepkg"
)

const subFolder = "gametypes"

// FieldInfo describes a single field on a game or player state.
type FieldInfo struct {
	Name     string `json:"name"`
	Type     string `json:"type"`
	DeckName string `json:"deckName,omitempty"`
	EnumName string `json:"enumName,omitempty"`
}

// DeckInfo describes a deck and its component value fields.
type DeckInfo struct {
	Name   string      `json:"name"`
	Fields []FieldInfo `json:"fields"`
}

// EnumInfo describes an enum and its string values.
type EnumInfo struct {
	Name   string   `json:"name"`
	Values []string `json:"values"`
}

// TypeResult is the result of extracting type information for a single game package.
type TypeResult struct {
	PackageName  string      `json:"packageName"`
	ImportPath   string      `json:"importPath"`
	GameFields   []FieldInfo `json:"gameFields"`
	PlayerFields []FieldInfo `json:"playerFields"`
	Decks        []DeckInfo  `json:"decks"`
	Enums        []EnumInfo  `json:"enums"`
}

// Build generates a temporary Go binary that imports all game packages,
// instantiates GameManagers with in-memory storage, and extracts type
// information. It returns the results as a slice of TypeResult.
func Build(directory string, pkgs []*gamepkg.Pkg) ([]TypeResult, error) {

	if _, err := os.Stat(directory); os.IsNotExist(err) {
		return nil, fmt.Errorf("the provided directory %s does not exist", directory)
	}

	code, err := Code(pkgs)

	if err != nil {
		return nil, fmt.Errorf("couldn't generate code: %w", err)
	}

	dir := filepath.Join(directory, subFolder)

	if _, err := os.Stat(dir); os.IsNotExist(err) {
		if err := os.Mkdir(dir, 0700); err != nil {
			return nil, fmt.Errorf("couldn't create gametypes directory: %w", err)
		}
	}

	codePath := filepath.Join(dir, "main.go")

	if err := os.WriteFile(codePath, code, 0644); err != nil {
		return nil, fmt.Errorf("couldn't save code: %w", err)
	}

	cmd := exec.Command("go", "build")
	cmd.Dir = dir

	errBuf := new(bytes.Buffer)
	cmd.Stderr = errBuf

	err = cmd.Run()

	if err != nil {
		return nil, fmt.Errorf("couldn't build gametypes binary: %w: %s", err, errBuf.String())
	}

	binaryName := filepath.Join(dir, subFolder)

	if _, err := os.Stat(binaryName); os.IsNotExist(err) {
		return nil, fmt.Errorf("sanity check failed: binary does not appear to have been created")
	}

	absBinaryName, err := filepath.Abs(binaryName)
	if err != nil {
		return nil, fmt.Errorf("couldn't get absolute path to binary: %w", err)
	}

	cmd = exec.Command(absBinaryName)
	cmd.Dir = dir

	outBuf := new(bytes.Buffer)
	errBuf = new(bytes.Buffer)
	cmd.Stdout = outBuf
	cmd.Stderr = errBuf

	err = cmd.Run()

	if err != nil {
		return nil, fmt.Errorf("couldn't run gametypes binary: %w: %s", err, errBuf.String())
	}

	var results []TypeResult

	if err := json.Unmarshal(outBuf.Bytes(), &results); err != nil {
		return nil, fmt.Errorf("couldn't parse gametypes output: %w", err)
	}

	return results, nil
}

// Code returns the source code for a temporary Go binary that extracts type
// information from the given game packages.
func Code(pkgs []*gamepkg.Pkg) ([]byte, error) {

	buf := new(bytes.Buffer)

	err := codeTemplate.Execute(buf, map[string]interface{}{
		"pkgs": pkgs,
	})

	if err != nil {
		return nil, fmt.Errorf("couldn't execute code template: %w", err)
	}

	formatted, err := format.Source(buf.Bytes())

	if err != nil {
		return nil, fmt.Errorf("couldn't format code output: %w", err)
	}

	return formatted, nil
}

var codeTemplate = template.Must(template.New("gametypes").Parse(codeTemplateText))

var codeTemplateText = `/*

A temporary binary generated by boardgame-util to extract type information from game packages.

*/
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"reflect"
	"sort"
	"strings"

	"github.com/jkomoros/boardgame"
	memorystorage "github.com/jkomoros/boardgame/storage/memory"
	{{- range .pkgs}}
	"{{.Import}}"
	{{- end}}
)

type fieldInfo struct {
	Name     string ` + "`" + `json:"name"` + "`" + `
	Type     string ` + "`" + `json:"type"` + "`" + `
	DeckName string ` + "`" + `json:"deckName,omitempty"` + "`" + `
	EnumName string ` + "`" + `json:"enumName,omitempty"` + "`" + `
}

type deckInfo struct {
	Name   string      ` + "`" + `json:"name"` + "`" + `
	Fields []fieldInfo ` + "`" + `json:"fields"` + "`" + `
}

type enumInfo struct {
	Name   string   ` + "`" + `json:"name"` + "`" + `
	Values []string ` + "`" + `json:"values"` + "`" + `
}

type typeResult struct {
	PackageName  string      ` + "`" + `json:"packageName"` + "`" + `
	ImportPath   string      ` + "`" + `json:"importPath"` + "`" + `
	GameFields   []fieldInfo ` + "`" + `json:"gameFields"` + "`" + `
	PlayerFields []fieldInfo ` + "`" + `json:"playerFields"` + "`" + `
	Decks        []deckInfo  ` + "`" + `json:"decks"` + "`" + `
	Enums        []enumInfo  ` + "`" + `json:"enums"` + "`" + `
}

type delegateEntry struct {
	delegate   boardgame.GameDelegate
	importPath string
}

func extractFields(reader boardgame.PropertyReader, concreteType reflect.Type) []fieldInfo {
	props := reader.Props()

	// Sort field names for deterministic output
	names := make([]string, 0, len(props))
	for name := range props {
		names = append(names, name)
	}
	sort.Strings(names)

	var fields []fieldInfo
	for _, name := range names {
		propType := props[name]

		fi := fieldInfo{
			Name: name,
			Type: propType.String(),
		}

		// Look for struct tags to find deck/enum associations.
		// FieldByName handles embedded structs automatically.
		tag := findStructTag(concreteType, name)
		if tag != "" {
			// Parse stack/sizedstack tags for deck name
			if stackTag := reflect.StructTag(tag).Get("stack"); stackTag != "" {
				parts := strings.Split(stackTag, ",")
				fi.DeckName = parts[0]
			}
			if sizedTag := reflect.StructTag(tag).Get("sizedstack"); sizedTag != "" {
				parts := strings.Split(sizedTag, ",")
				fi.DeckName = parts[0]
			}
			// Parse overlap/concatenate tags for merged stacks
			if overlapTag := reflect.StructTag(tag).Get("overlap"); overlapTag != "" {
				fi.DeckName = resolveMergedStackDeck(concreteType, overlapTag)
			}
			if concatTag := reflect.StructTag(tag).Get("concatenate"); concatTag != "" {
				fi.DeckName = resolveMergedStackDeck(concreteType, concatTag)
			}
			// Parse enum tag
			if enumTag := reflect.StructTag(tag).Get("enum"); enumTag != "" {
				fi.EnumName = enumTag
			}
		}

		fields = append(fields, fi)
	}

	return fields
}

// findStructTag searches for a field by name in the given type (including
// embedded structs via FieldByName) and returns its raw struct tag string.
func findStructTag(t reflect.Type, fieldName string) string {
	if t.Kind() == reflect.Ptr {
		t = t.Elem()
	}
	if t.Kind() != reflect.Struct {
		return ""
	}

	if f, ok := t.FieldByName(fieldName); ok {
		return string(f.Tag)
	}

	return ""
}

// resolveMergedStackDeck resolves the deck name for a MergedStack by looking
// at the first referenced field's stack/sizedstack tag.
func resolveMergedStackDeck(t reflect.Type, tagValue string) string {
	if t.Kind() == reflect.Ptr {
		t = t.Elem()
	}
	if tagValue == "" {
		return ""
	}
	parts := strings.Split(tagValue, ",")
	refFieldName := strings.TrimSpace(parts[0])
	tag := findStructTag(t, refFieldName)
	if tag == "" {
		return ""
	}
	if stackTag := reflect.StructTag(tag).Get("stack"); stackTag != "" {
		sParts := strings.Split(stackTag, ",")
		return sParts[0]
	}
	if sizedTag := reflect.StructTag(tag).Get("sizedstack"); sizedTag != "" {
		sParts := strings.Split(sizedTag, ",")
		return sParts[0]
	}
	return ""
}

func main() {
	entries := []delegateEntry{
		{{- range .pkgs}}
		{delegate: {{.Name}}.NewDelegate(), importPath: "{{.Import}}"},
		{{- end}}
	}

	var results []typeResult

	for _, entry := range entries {
		storage := memorystorage.NewStorageManager()
		manager, err := boardgame.NewGameManager(entry.delegate, storage)
		if err != nil {
			fmt.Fprintf(os.Stderr, "Warning: couldn't create manager for %s: %v\n", entry.delegate.Name(), err)
			continue
		}

		// Extract game state fields
		gameStateConstructor := entry.delegate.GameStateConstructor()
		gameReader, ok := gameStateConstructor.(boardgame.Reader)
		if !ok {
			fmt.Fprintf(os.Stderr, "Warning: GameState for %s does not implement Reader, skipping\n", entry.delegate.Name())
			continue
		}
		gameConcreteType := reflect.TypeOf(gameStateConstructor)
		gameFields := extractFields(gameReader.Reader(), gameConcreteType)

		// Extract player state fields
		playerStateConstructor := entry.delegate.PlayerStateConstructor(0)
		playerReader, ok := playerStateConstructor.(boardgame.Reader)
		if !ok {
			fmt.Fprintf(os.Stderr, "Warning: PlayerState for %s does not implement Reader, skipping\n", entry.delegate.Name())
			continue
		}
		playerConcreteType := reflect.TypeOf(playerStateConstructor)
		playerFields := extractFields(playerReader.Reader(), playerConcreteType)

		// Extract deck component value fields
		chest := manager.Chest()
		deckNames := chest.DeckNames()
		sort.Strings(deckNames)

		var decks []deckInfo
		for _, deckName := range deckNames {
			deck := chest.Deck(deckName)
			if deck == nil {
				continue
			}

			di := deckInfo{Name: deckName}

			if deck.Len() > 0 {
				component := deck.ComponentAt(0)
				if component != nil {
					vals := component.Values()
					if vals != nil {
						valReader, ok := vals.(boardgame.Reader)
						if ok {
							valConcreteType := reflect.TypeOf(vals)
							di.Fields = extractFields(valReader.Reader(), valConcreteType)
						}
					}
				}
			}

			decks = append(decks, di)
		}

		// Extract enum information
		var enums []enumInfo
		enumSet := chest.Enums()
		if enumSet != nil {
			enumNames := enumSet.EnumNames()
			sort.Strings(enumNames)
			for _, enumName := range enumNames {
				e := enumSet.Enum(enumName)
				if e == nil {
					continue
				}
				vals := e.Values()

				// For tree enums, filter to leaf values only.
				if treeEnum := e.TreeEnum(); treeEnum != nil {
					n := 0
					for _, v := range vals {
						if treeEnum.IsLeaf(v) {
							vals[n] = v
							n++
						}
					}
					vals = vals[:n]
				}

				sort.Slice(vals, func(i, j int) bool { return vals[i] < vals[j] })

				var strVals []string
				for _, v := range vals {
					strVals = append(strVals, e.String(v))
				}

				enums = append(enums, enumInfo{
					Name:   enumName,
					Values: strVals,
				})
			}
		}

		results = append(results, typeResult{
			PackageName:  entry.delegate.Name(),
			ImportPath:   entry.importPath,
			GameFields:   gameFields,
			PlayerFields: playerFields,
			Decks:        decks,
			Enums:        enums,
		})
	}

	encoder := json.NewEncoder(os.Stdout)
	if err := encoder.Encode(results); err != nil {
		fmt.Fprintf(os.Stderr, "Error encoding results: %v\n", err)
		os.Exit(1)
	}
}
`
