const (
	maxAuthoredBoardBytes     = 2 * 1024 * 1024
	generatedBoardSpaceHeader = "/* Auto-generated by boardgame-util from "
)

type emitBoardSpaces struct {
	baseSubCommand
	Check bool
}

type authoredBoardSpace struct {
	Key     string
	Label   string
	Order   int
	Numeric bool
}

type generatedBoardSpacesFile struct {
	path     string
	contents []byte
}

func (e *emitBoardSpaces) Name() string { return "emit-board-spaces" }
func (e *emitBoardSpaces) Description() string {
	return "Generates literal TypeScript space keys from authored SVG boards"
}
func (e *emitBoardSpaces) HelpText() string {
	return e.Name() + ` scans configured game client SVG files for data-board-space,
accessible labels, and optional data-board-order. Each authored board produces a
literal-key TypeScript contract (_board_spaces.ts for board.svg), so SVG key
renames become strict compile failures instead of runtime-empty interaction.
Keys are strings unless the SVG root explicitly sets data-board-key-type="number".`
}
func (e *emitBoardSpaces) WritOptions() []*writ.Option {
	return []*writ.Option{{Names: []string{"check"}, Description: "Verify generated board-space contracts are current without writing files.", Decoder: writ.NewFlagDecoder(&e.Check), Flag: true}}
}
func (e *emitBoardSpaces) Run(_ writ.Path, _ []string) {
	packages, err := e.Base().GetConfig(false).Dev.AllGamePackages()
	if err != nil {
		e.Base().errAndQuit("Not all game packages were valid: " + err.Error())
	}
	if err := emitBoardSpacesForPackages(packages, e.Check); err != nil {
		e.Base().errAndQuit("Couldn't emit board spaces: " + err.Error())
	}
	if e.Check {
		fmt.Println("Generated board-space contracts are current")
	} else {
		fmt.Println("Successfully generated board-space contracts")
	}
}

func emitBoardSpacesForPackages(packages []*gamepkg.Pkg, check bool) error {
	generated, orphans, err := generateBoardSpacesForPackages(packages, check)
	if err != nil {
		return err
	}
	return installGeneratedBoardSpaces(generated, orphans, check)
}

func generateBoardSpacesForPackages(packages []*gamepkg.Pkg, includeReadOnly bool) ([]generatedBoardSpacesFile, []string, error) {
	var generated []generatedBoardSpacesFile
	var orphans []string
	destinations := map[string]string{}
	for _, pkg := range packages {
		client := pkg.ClientFolder()
		if client == "" || (pkg.ReadOnly() && !includeReadOnly) {
			continue
		}
		files, desired, err := collectGeneratedBoardSpaces(client, destinations)
		if err != nil {
			return nil, nil, fmt.Errorf("%s: %w", pkg.Import(), err)
		}
		generated = append(generated, files...)
		found, err := orphanBoardSpaceContracts(client, desired)
		if err != nil {
			return nil, nil, fmt.Errorf("%s: %w", pkg.Import(), err)
		}
		orphans = append(orphans, found...)
	}
	sort.Slice(generated, func(i, j int) bool { return generated[i].path < generated[j].path })
	sort.Strings(orphans)
	return generated, orphans, nil
}

func installGeneratedBoardSpaces(generated []generatedBoardSpacesFile, orphans []string, check bool) error {
	if check {
		stale := append([]string(nil), orphans...)
		for _, file := range generated {
			current, err := os.ReadFile(file.path)
			if err != nil || !bytes.Equal(current, file.contents) {
				stale = append(stale, file.path)
			}
		}
		sort.Strings(stale)
		if len(stale) > 0 {
			return staleGeneratedClientContracts("generated board-space contracts are stale: " + strings.Join(stale, ", "))
		}
		return nil
	}
	files := make(map[string]fileutil.FileSpec, len(generated)+len(orphans))
	for _, file := range generated {
		if _, exists := files[file.path]; exists {
			return fmt.Errorf("duplicate generated board-space destination %s", file.path)
		}
		files[file.path] = fileutil.FileSpec{Contents: file.contents, Mode: 0o644, ForceMode: true}
	}
	for _, path := range orphans {
		if _, exists := files[path]; exists {
			return fmt.Errorf("generated board-space destination %s is also marked as an orphan", path)
		}
		files[path] = fileutil.FileSpec{Delete: true, RequireExisting: true}
	}
	if err := fileutil.WriteFileSetAtomicAbsolute(files, true); err != nil {
		return fmt.Errorf("install generated board-space contracts: %w", err)
	}
	for _, file := range generated {
		fmt.Printf("  Generated %s (%d bytes)\n", file.path, len(file.contents))
	}
	for _, path := range orphans {
		fmt.Printf("  Removed orphan %s\n", path)
	}
	return nil
}

func collectGeneratedBoardSpaces(client string, destinations map[string]string) ([]generatedBoardSpacesFile, map[string]bool, error) {
	var generated []generatedBoardSpacesFile
	desired := map[string]bool{}
	err := filepath.WalkDir(client, func(path string, entry os.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() || strings.ToLower(filepath.Ext(path)) != ".svg" {
			return nil
		}
		spaces, err := parseAuthoredBoardSpaces(path)
		if err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
		if len(spaces) == 0 {
			return nil
		}
		name := safeBoardContractName(strings.TrimSuffix(filepath.Base(path), filepath.Ext(path)))
		if name == "" {
			return fmt.Errorf("%s: SVG filename has no usable contract name", path)
		}
		output := "_" + name + "_spaces.ts"
		if name == "board" {
			output = "_board_spaces.ts"
		}
		destination := filepath.Join(filepath.Dir(path), output)
		if prior, exists := destinations[destination]; exists {
			return fmt.Errorf("board SVG output collision: %s and %s both generate %s", prior, path, destination)
		}
		destinations[destination] = path
		desired[destination] = true
		generated = append(generated, generatedBoardSpacesFile{path: destination, contents: generateBoardSpacesTypeScript(path, spaces)})
		return nil
	})
	return generated, desired, err
}

func orphanBoardSpaceContracts(client string, desired map[string]bool) ([]string, error) {
	var result []string
	err := filepath.WalkDir(client, func(path string, entry os.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() || desired[path] || !strings.HasPrefix(entry.Name(), "_") || !strings.HasSuffix(entry.Name(), "_spaces.ts") {
			return nil
		}
		contents, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		firstLine, _, _ := strings.Cut(string(contents), "\n")
		if strings.HasPrefix(firstLine, generatedBoardSpaceHeader) && strings.HasSuffix(firstLine, ". DO NOT EDIT. */") {
			result = append(result, path)
		}
		return nil
	})
	sort.Strings(result)
	return result, err
}

func parseAuthoredBoardSpaces(path string) ([]authoredBoardSpace, error) {
	info, err := os.Stat(path)
	if err != nil {
		return nil, err
	}
	if info.Size() > maxAuthoredBoardBytes {
		return nil, fmt.Errorf("SVG exceeds the %d-byte limit", maxAuthoredBoardBytes)
	}
	file, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer file.Close()
	decoder := xml.NewDecoder(io.LimitReader(file, maxAuthoredBoardBytes+1))
	var result []authoredBoardSpace
	keys := map[string]bool{}
	orders := map[int]bool{}
	depth := 0
	rootSeen := false
	var rootErr error
	numericKeys := false
	type pendingSpace struct {
		space             authoredBoardSpace
		depth, titleDepth int
		title             strings.Builder
	}
	var pending *pendingSpace
	for {
		token, err := decoder.Token()
		if err == io.EOF {
			break
		}
		if err != nil {
			return nil, fmt.Errorf("invalid SVG XML: %w", err)
		}
		switch value := token.(type) {
		case xml.Directive:
			if strings.Contains(strings.ToLower(string(value)), "doctype") {
				return nil, fmt.Errorf("SVG document types are not allowed")
			}
		case xml.CharData:
			if pending != nil && pending.titleDepth > 0 {
				pending.title.Write(value)
			}
		case xml.StartElement:
			depth++
			attrs := map[string]string{}
			for _, attr := range value.Attr {
				if attr.Name.Space == "" {
					attrs[attr.Name.Local] = attr.Value
				}
			}
			if !rootSeen {
				rootSeen = true
				if value.Name.Local != "svg" || value.Name.Space != "http://www.w3.org/2000/svg" {
					rootErr = fmt.Errorf("document root must be an SVG namespace svg element")
				}
				viewBox := strings.Fields(strings.ReplaceAll(attrs["viewBox"], ",", " "))
				if len(viewBox) != 4 {
					if rootErr == nil {
						rootErr = fmt.Errorf("SVG must have a four-number viewBox")
					}
				} else {
					for index, raw := range viewBox {
						number, err := strconv.ParseFloat(raw, 64)
						if err != nil || math.IsNaN(number) || math.IsInf(number, 0) || (index >= 2 && number <= 0) {
							if rootErr == nil {
								rootErr = fmt.Errorf("SVG must have a finite viewBox with positive width and height")
							}
							break
						}
					}
				}
				switch attrs["data-board-key-type"] {
				case "", "string":
				case "number":
					numericKeys = true
				default:
					return nil, fmt.Errorf("invalid data-board-key-type %q", attrs["data-board-key-type"])
				}
			}
			if pending != nil && depth == pending.depth+1 && value.Name.Local == "title" {
				pending.titleDepth = depth
				continue
			}
			key, found := attrs["data-board-space"]
			if !found {
				continue
			}
			if pending != nil {
				return nil, fmt.Errorf("nested data-board-space regions are not supported")
			}
			if key == "" || keys[key] {
				return nil, fmt.Errorf("empty or duplicate data-board-space %q", key)
			}
			label := strings.TrimSpace(attrs["data-board-label"])
			if label == "" {
				label = strings.TrimSpace(attrs["aria-label"])
			}
			order := len(keys)
			if raw, exists := attrs["data-board-order"]; exists {
				order, err = strconv.Atoi(raw)
				if err != nil || order < 0 {
					return nil, fmt.Errorf("space %q has invalid data-board-order %q", key, raw)
				}
			}
			if orders[order] {
				return nil, fmt.Errorf("duplicate data-board-order %d", order)
			}
			if numericKeys {
				number, parseErr := strconv.ParseInt(key, 10, 64)
				if parseErr != nil || strconv.FormatInt(number, 10) != key || number < -9007199254740991 || number > 9007199254740991 {
					return nil, fmt.Errorf("space %q is not a canonical JavaScript-safe integer required by data-board-key-type=number", key)
				}
			}
			keys[key], orders[order] = true, true
			pending = &pendingSpace{space: authoredBoardSpace{Key: key, Label: label, Order: order, Numeric: numericKeys}, depth: depth}
		case xml.EndElement:
			if pending != nil && pending.titleDepth == depth {
				pending.titleDepth = 0
			}
			if pending != nil && pending.depth == depth {
				if pending.space.Label == "" {
					pending.space.Label = strings.TrimSpace(pending.title.String())
				}
				if pending.space.Label == "" {
					return nil, fmt.Errorf("space %q requires data-board-label, aria-label, or a direct title", pending.space.Key)
				}
				result = append(result, pending.space)
				pending = nil
			}
			depth--
		}
	}
	if !rootSeen {
		return nil, fmt.Errorf("SVG was empty")
	}
	if len(result) > 0 && rootErr != nil {
		return nil, rootErr
	}
	sort.Slice(result, func(i, j int) bool { return result[i].Order < result[j].Order })
	return result, nil
}

func generateBoardSpacesTypeScript(source string, spaces []authoredBoardSpace) []byte {
	var out strings.Builder
	out.WriteString(generatedBoardSpaceHeader + filepath.Base(source) + ". DO NOT EDIT. */\n\n")
	out.WriteString("export const BoardSpaceKeys = [")
	for index, space := range spaces {
		if index > 0 {
			out.WriteString(", ")
		}
		if space.Numeric {
			out.WriteString(space.Key)
		} else {
			encoded, _ := json.Marshal(space.Key)
			out.Write(encoded)
		}
	}
	out.WriteString("] as const;\n\nexport type BoardSpaceKey = (typeof BoardSpaceKeys)[number];\n\n")
	out.WriteString("export const BoardSpaceLabels = {\n")
	for _, space := range spaces {
		key, _ := json.Marshal(space.Key)
		label, _ := json.Marshal(space.Label)
		fmt.Fprintf(&out, "  %s: %s,\n", key, label)
	}
	out.WriteString("} as const satisfies Readonly<Record<string, string>>;\n")
	return []byte(out.String())
}

func safeBoardContractName(value string) string {
	return strings.Map(func(r rune) rune {
		if unicode.IsLetter(r) || unicode.IsDigit(r) || r == '_' {
			return unicode.ToLower(r)
		}
		return '_'
	}, value)
}
