import { test, expect } from '@playwright/test';

/**
 * A TOKEN SHOWS WHAT `tokenView({render})` PUTS IN IT.
 *
 * `componentView`'s `render` option writes its result into the host's LIGHT DOM
 * (`updateComponentFromView` in component-view.ts). Light DOM is only visible
 * if the shadow root offers it a `<slot>`. `boardgame-card` has three and
 * `boardgame-component` -- the base class -- has one, but `BoardgameToken`
 * overrode `render()` to emit `#outer > #inner > (#solid | #art)` and dropped
 * the slot entirely.
 *
 * So `tokenView({ render: … })` type-checked, ran on every snapshot, mutated
 * the token's light DOM, and painted nothing at all. Nothing threw and nothing
 * warned; the label was simply never on screen.
 *
 * The slot goes INSIDE `#inner`, as a sibling of `#solid`/`#art` rather than
 * inside either, and paints over them:
 *
 *   - Inside `#solid` it would become a seventh facet: the facets are
 *     absolutely-positioned projected polygons with per-facet `clip-path`,
 *     generated by src/solid/flat-facets.ts, and a text node dropped among
 *     them would be clipped and skewed by whatever facet geometry it landed in.
 *   - Inside `#art` it would inherit that wrapper's `drop-shadow` edge filter
 *     and, for meeple/pawn, its `scaleY` lean -- a label is not part of the
 *     silhouette being given depth.
 *   - `#inner` is the token's own square box and the frame both the solid and
 *     the art are drawn into, so it is the one place a caption sits in the
 *     token's plane, at the token's size, over whatever shape is underneath.
 */

test.describe('a token\'s slotted content', () => {
  test.beforeEach(async ({ page }) => {
    await page.goto('/');
  });

  test('is assigned to a slot and paints over the shape', async ({ page }) => {
    const measured = await page.evaluate(async () => {
      await import('/src/components/boardgame-token.ts');
      document.body.innerHTML = '';

      const out: Record<string, { assigned: boolean; width: number; height: number; visible: boolean }> = {};

      // 'cube' renders as a generated 3D solid; 'meeple' renders as authored
      // art. Both paths must offer the slot -- the bug was in render(), which
      // is shared.
      for (const type of ['cube', 'meeple']) {
        const el = document.createElement('boardgame-token') as any;
        el.type = type;
        el.item = { ID: type };
        const label = document.createElement('span');
        label.textContent = 'SLOTTED';
        label.setAttribute('data-probe', '');
        label.style.fontSize = '10px';
        el.appendChild(label);
        document.body.appendChild(el);
        await el.updateComplete;

        const box = label.getBoundingClientRect();
        out[type] = {
          assigned: label.assignedSlot !== null,
          width: box.width,
          height: box.height,
          visible: getComputedStyle(label).visibility !== 'hidden',
        };
      }
      return out;
    });

    for (const type of ['cube', 'meeple']) {
      const result = measured[type];
      expect(result.assigned, `<${type}> token must assign light DOM to a slot`).toBe(true);
      expect(result.width, `<${type}> token's slotted content must have a painted width`).toBeGreaterThan(0);
      expect(result.height, `<${type}> token's slotted content must have a painted height`).toBeGreaterThan(0);
      expect(result.visible, `<${type}> token's slotted content must be visible`).toBe(true);
    }
  });

  test('sits over the shape, not inside its geometry', async ({ page }) => {
    const placement = await page.evaluate(async () => {
      await import('/src/components/boardgame-token.ts');
      document.body.innerHTML = '';

      const el = document.createElement('boardgame-token') as any;
      el.type = 'cube';
      el.item = { ID: 'cube' };
      const label = document.createElement('span');
      label.textContent = 'X';
      el.appendChild(label);
      document.body.appendChild(el);
      await el.updateComplete;

      const slot = el.shadowRoot.querySelector('slot') as HTMLSlotElement;
      const inner = el.shadowRoot.querySelector('#inner') as HTMLElement;
      const overlay = slot.parentElement as HTMLElement;
      const overlayBox = overlay.getBoundingClientRect();
      const innerBox = inner.getBoundingClientRect();
      return {
        // A slot nested in the solid or the art wrapper would report those.
        insideSolid: slot.closest('#solid') !== null,
        insideArt: slot.closest('#art') !== null,
        // The overlay lives directly in #inner and covers exactly its box, so
        // content is drawn in the token's plane at the token's size.
        overlayParentIsInner: overlay.parentElement === inner,
        overlayPosition: getComputedStyle(overlay).position,
        overlayPointerEvents: getComputedStyle(overlay).pointerEvents,
        coversInner:
          Math.abs(overlayBox.width - innerBox.width) < 0.5 &&
          Math.abs(overlayBox.height - innerBox.height) < 0.5,
        innerWidth: innerBox.width,
      };
    });

    expect(placement.insideSolid).toBe(false);
    expect(placement.insideArt).toBe(false);
    expect(placement.overlayParentIsInner).toBe(true);
    // Absolute so a caption can never grow #inner: the square box is the
    // stack's layout contract (token-box.spec.ts).
    expect(placement.overlayPosition).toBe('absolute');
    // The overlay must not swallow the tap #outer is listening for.
    expect(placement.overlayPointerEvents).toBe('none');
    expect(placement.innerWidth).toBeGreaterThan(0);
    expect(placement.coversInner).toBe(true);
  });
});
