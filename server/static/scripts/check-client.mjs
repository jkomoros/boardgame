#!/usr/bin/env node

import process from 'node:process';
import path from 'node:path';
import ts from 'typescript';
import {
  DefaultLitAnalyzerContext,
  LitAnalyzer,
  makeConfig,
} from 'lit-analyzer';

const VERSION = 1;
const REQUIRED_COMPILER_OPTIONS = Object.freeze({
  strict: true,
  noUncheckedIndexedAccess: true,
  exactOptionalPropertyTypes: true,
  noPropertyAccessFromIndexSignature: true,
  noImplicitOverride: true,
  useUnknownInCatchVariables: true,
  noImplicitReturns: true,
  noFallthroughCasesInSwitch: true,
  noUnusedLocals: true,
  noUnusedParameters: true,
  noEmit: true,
});
const GENERATED_CLIENT_BASENAMES = new Set([
  '_game_renderer.ts',
  '_move_args.ts',
  '_move_names.ts',
  '_types.ts',
]);
const GENERATED_CLIENT_HEADER = '/*\n * Auto-generated by boardgame-util. DO NOT EDIT.\n */\n';
const FACADE_COMPONENT_MODULES = new Set([
  'boardgame-action-bar',
  'boardgame-action-button',
  'boardgame-board-viewport',
  'boardgame-card',
  'boardgame-component-stack',
  'boardgame-component-zone',
  'boardgame-die',
  'boardgame-draft-controls',
  'boardgame-fading-text',
  'boardgame-game-board',
  'boardgame-game-outcome',
  'boardgame-game-surface',
  'boardgame-hand-view-base',
  'boardgame-inspector',
  'boardgame-placement-item',
  'boardgame-player-grid',
  'boardgame-player-badge',
  'boardgame-player-panel',
  'boardgame-readiness',
  'boardgame-selection-option',
  'boardgame-spatial-board',
  'boardgame-status-text',
  'boardgame-table-view-base',
  'boardgame-target-list',
  'boardgame-timer',
  'boardgame-token',
  'boardgame-turn-status',
  'companion-avatar-catalog',
]);
const POLICY_MESSAGES = Object.freeze({
  BGCLIENT0101: 'Explicit any is not allowed in creator code; use a precise type or unknown and narrow it.',
  BGCLIENT0102: '@ts-ignore is not allowed in creator code; fix the error or use an explained @ts-expect-error.',
  BGCLIENT0103: '@ts-expect-error requires an explanation on the same line.',
  BGCLIENT0104: 'Nested TypeScript assertions are not allowed; narrow or validate the value instead.',
  BGCLIENT0105: 'Public renderer APIs are exposed by the client facade; import from src/client.js instead of a deep component module.',
});

function posixPath(value) {
  return value.split(path.sep).join('/');
}

function displayPath(value, baseDirectory) {
  const relative = path.relative(baseDirectory, value);
  return posixPath(relative || path.basename(value));
}

function categoryName(category) {
  return ts.DiagnosticCategory[category]?.toLowerCase() ?? 'error';
}

function serializeDiagnostic(diagnostic, baseDirectory) {
  const result = {
    source: 'typescript',
    code: `TS${diagnostic.code}`,
    category: categoryName(diagnostic.category),
    message: ts.flattenDiagnosticMessageText(diagnostic.messageText, '\n'),
  };

  if (diagnostic.file) {
    result.file = displayPath(diagnostic.file.fileName, baseDirectory);
    if (diagnostic.start !== undefined) {
      const location = diagnostic.file.getLineAndCharacterOfPosition(diagnostic.start);
      result.line = location.line + 1;
      result.column = location.character + 1;
    }
  }

  return result;
}

function serializeLitDiagnostic(diagnostic, baseDirectory) {
  const location = diagnostic.file.getLineAndCharacterOfPosition(diagnostic.location.start);
  return {
    source: 'lit',
    code: `LIT-${diagnostic.source}`,
    category: diagnostic.severity,
    message: diagnostic.message,
    file: displayPath(diagnostic.file.fileName, baseDirectory),
    line: location.line + 1,
    column: location.character + 1,
  };
}

function litDiagnostics(program, rootNames, baseDirectory) {
  const roots = new Set(rootNames.map((fileName) => path.resolve(fileName)));
  const context = new DefaultLitAnalyzerContext({
    ts,
    getProgram: () => program,
  });
  context.updateConfig(makeConfig({
    strict: false,
    cwd: baseDirectory,
    dontShowSuggestions: true,
    dontSuggestConfigChanges: true,
    rules: {
      'no-unknown-property': 'error',
      'no-incompatible-type-binding': 'error',
      'no-complex-attribute-binding': 'error',
      'no-noncallable-event-binding': 'error',
    },
  }));
  const analyzer = new LitAnalyzer(context);
  const diagnostics = [];
  for (const sourceFile of program.getSourceFiles()) {
    if (!roots.has(path.resolve(sourceFile.fileName)) || sourceFile.isDeclarationFile) {
      continue;
    }
    diagnostics.push(...analyzer.getDiagnosticsInFile(sourceFile)
      .map((diagnostic) => serializeLitDiagnostic(diagnostic, baseDirectory)));
  }
  return diagnostics;
}

function policyDiagnostic(code, sourceFile, position, baseDirectory) {
  const location = sourceFile.getLineAndCharacterOfPosition(position);
  return {
    source: 'boardgame-client',
    code,
    category: 'error',
    message: POLICY_MESSAGES[code],
    file: displayPath(sourceFile.fileName, baseDirectory),
    line: location.line + 1,
    column: location.character + 1,
  };
}

function commentPolicyDiagnostics(sourceFile, baseDirectory) {
  const diagnostics = [];
  const scanner = ts.createScanner(
    sourceFile.languageVersion,
    false,
    sourceFile.languageVariant,
    sourceFile.text,
  );
  for (let token = scanner.scan(); token !== ts.SyntaxKind.EndOfFileToken; token = scanner.scan()) {
    if (token !== ts.SyntaxKind.SingleLineCommentTrivia
      && token !== ts.SyntaxKind.MultiLineCommentTrivia) {
      continue;
    }
    const commentStart = scanner.getTokenPos();
    const comment = scanner.getTokenText();
    for (const match of comment.matchAll(/@ts-ignore\b/g)) {
      diagnostics.push(policyDiagnostic(
        'BGCLIENT0102',
        sourceFile,
        commentStart + match.index,
        baseDirectory,
      ));
    }
    for (const match of comment.matchAll(/@ts-expect-error\b([^\r\n]*)/g)) {
      const explanation = match[1]
        .replace(/\*\/\s*$/, '')
        .replace(/^[\s:\-]+/, '')
        .trim();
      if (!explanation) {
        diagnostics.push(policyDiagnostic(
          'BGCLIENT0103',
          sourceFile,
          commentStart + match.index,
          baseDirectory,
        ));
      }
    }
  }
  return diagnostics;
}

function unwrapParentheses(node) {
  let current = node;
  while (ts.isParenthesizedExpression(current)) {
    current = current.expression;
  }
  return current;
}

function astPolicyDiagnostics(sourceFile, baseDirectory) {
  const diagnostics = [];
  function visit(node) {
    if (ts.isImportDeclaration(node) && ts.isStringLiteral(node.moduleSpecifier)) {
      const match = node.moduleSpecifier.text.match(/(?:^|\/)src\/components\/([^/]+?)(?:\.(?:js|ts))?$/);
      if (match && FACADE_COMPONENT_MODULES.has(match[1])) {
        diagnostics.push(policyDiagnostic(
          'BGCLIENT0105',
          sourceFile,
          node.moduleSpecifier.getStart(sourceFile),
          baseDirectory,
        ));
      }
    }
    if (node.kind === ts.SyntaxKind.AnyKeyword) {
      diagnostics.push(policyDiagnostic(
        'BGCLIENT0101',
        sourceFile,
        node.getStart(sourceFile),
        baseDirectory,
      ));
    }
    if (ts.isAsExpression(node) || ts.isTypeAssertionExpression(node)) {
      const assertedExpression = unwrapParentheses(node.expression);
      if (ts.isAsExpression(assertedExpression)
        || ts.isTypeAssertionExpression(assertedExpression)) {
        diagnostics.push(policyDiagnostic(
          'BGCLIENT0104',
          sourceFile,
          node.getStart(sourceFile),
          baseDirectory,
        ));
      }
    }
    ts.forEachChild(node, visit);
  }
  visit(sourceFile);
  return diagnostics;
}

function creatorPolicyDiagnostics(program, rootNames, baseDirectory) {
  const roots = new Set(rootNames.map((fileName) => path.resolve(fileName)));
  const diagnostics = [];
  for (const sourceFile of program.getSourceFiles()) {
    if (!roots.has(path.resolve(sourceFile.fileName))
      || sourceFile.isDeclarationFile
      || isGeneratedClientSource(sourceFile, baseDirectory)) {
      continue;
    }
    diagnostics.push(...commentPolicyDiagnostics(sourceFile, baseDirectory));
    diagnostics.push(...astPolicyDiagnostics(sourceFile, baseDirectory));
  }
  return diagnostics;
}

function isGeneratedClientSource(sourceFile, baseDirectory) {
  const basename = path.basename(sourceFile.fileName);
  return GENERATED_CLIENT_BASENAMES.has(basename)
    && displayPath(sourceFile.fileName, baseDirectory) === `client/${basename}`
    && sourceFile.text.startsWith(GENERATED_CLIENT_HEADER);
}

function compareDiagnostics(left, right) {
  const leftFile = left.file ?? '';
  const rightFile = right.file ?? '';
  return (leftFile < rightFile ? -1 : leftFile > rightFile ? 1 : 0)
    || (left.line ?? 0) - (right.line ?? 0)
    || (left.column ?? 0) - (right.column ?? 0)
    || (left.code < right.code ? -1 : left.code > right.code ? 1 : 0)
    || (left.message < right.message ? -1 : left.message > right.message ? 1 : 0);
}

function parseArguments(argv) {
  let project;
  let creatorPolicy = false;
  let lit = false;
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === '--project') {
      project = argv[index + 1];
      index += 1;
    } else if (argument.startsWith('--project=')) {
      project = argument.slice('--project='.length);
    } else if (argument === '--creator-policy') {
      creatorPolicy = true;
    } else if (argument === '--lit') {
      lit = true;
    } else {
      throw new Error(`unknown argument: ${argument}`);
    }
  }
  if (!project) {
    throw new Error('missing required --project <tsconfig.json>');
  }
  return { project: path.resolve(project), creatorPolicy, lit };
}

function readProject(projectPath) {
  const readResult = ts.readConfigFile(projectPath, ts.sys.readFile);
  if (readResult.error) {
    return { diagnostics: [readResult.error] };
  }

  const parsed = ts.parseJsonConfigFileContent(
    readResult.config,
    ts.sys,
    path.dirname(projectPath),
    undefined,
    projectPath,
  );
  if (parsed.errors.length > 0) {
    return { diagnostics: parsed.errors };
  }
  return { parsed };
}

function emit(document) {
  process.stdout.write(`${JSON.stringify(document)}\n`);
}

function main() {
  let projectPath;
  let creatorPolicy;
  let lit;
  try {
    ({ project: projectPath, creatorPolicy, lit } = parseArguments(process.argv.slice(2)));
  } catch (error) {
    emit({
      version: VERSION,
      project: null,
      diagnostics: [],
      infrastructureError: error instanceof Error ? error.message : String(error),
    });
    return 2;
  }

  const baseDirectory = path.dirname(projectPath);
  const project = displayPath(projectPath, process.cwd());
  try {
    const loaded = readProject(projectPath);
    if (loaded.diagnostics) {
      const diagnostics = loaded.diagnostics
        .map((diagnostic) => serializeDiagnostic(diagnostic, baseDirectory))
        .sort(compareDiagnostics);
      emit({ version: VERSION, project, diagnostics });
      return 1;
    }

    const program = ts.createProgram({
      rootNames: loaded.parsed.fileNames,
      options: {
        ...loaded.parsed.options,
        ...REQUIRED_COMPILER_OPTIONS,
      },
      projectReferences: loaded.parsed.projectReferences,
    });
    const diagnostics = ts.getPreEmitDiagnostics(program)
      .map((diagnostic) => serializeDiagnostic(diagnostic, baseDirectory));
    if (creatorPolicy) {
      diagnostics.push(...creatorPolicyDiagnostics(
        program,
        loaded.parsed.fileNames,
        baseDirectory,
      ));
    }
    if (lit) {
      diagnostics.push(...litDiagnostics(program, loaded.parsed.fileNames, baseDirectory));
    }
    diagnostics.sort(compareDiagnostics);
    emit({ version: VERSION, project, diagnostics });
    return diagnostics.length === 0 ? 0 : 1;
  } catch (error) {
    emit({
      version: VERSION,
      project,
      diagnostics: [],
      infrastructureError: error instanceof Error ? error.message : String(error),
    });
    return 2;
  }
}

process.exitCode = main();
